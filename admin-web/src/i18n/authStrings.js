/** Ganti placeholder {nama} pada teks. */
export function fmt(text, vars = {}) {
  return String(text).replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`))
}

export function authText(lang) {
  return AUTH_STRINGS[lang] || AUTH_STRINGS.id
}
